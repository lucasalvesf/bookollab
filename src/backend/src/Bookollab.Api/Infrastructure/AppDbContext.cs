using Bookollab.Api.Domain.Chapters;
using Bookollab.Api.Domain.Characters;
using Bookollab.Api.Domain.Communities;
using Bookollab.Api.Domain.Scenes;
using Bookollab.Api.Domain.Users;
using Microsoft.AspNetCore.Identity;
using Microsoft.AspNetCore.Identity.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;

namespace Bookollab.Api.Infrastructure;

public sealed class AppDbContext(DbContextOptions<AppDbContext> options)
    : IdentityDbContext<User, IdentityRole<Guid>, Guid>(options)
{
    public DbSet<RefreshToken> RefreshTokens => Set<RefreshToken>();
    public DbSet<Community> Communities => Set<Community>();
    public DbSet<CommunityRole> CommunityRoles => Set<CommunityRole>();
    public DbSet<Membership> Memberships => Set<Membership>();
    public DbSet<JoinRequest> JoinRequests => Set<JoinRequest>();
    public DbSet<Invite> Invites => Set<Invite>();
    public DbSet<Character> Characters => Set<Character>();
    public DbSet<Scene> Scenes => Set<Scene>();
    public DbSet<SceneParticipant> SceneParticipants => Set<SceneParticipant>();
    public DbSet<SceneAction> SceneActions => Set<SceneAction>();
    public DbSet<SceneActionRevision> SceneActionRevisions => Set<SceneActionRevision>();
    public DbSet<Chapter> Chapters => Set<Chapter>();
    public DbSet<ChapterRevision> ChapterRevisions => Set<ChapterRevision>();
    public DbSet<Domain.Uploads.Upload> Uploads => Set<Domain.Uploads.Upload>();
    public DbSet<Domain.Encyclopedia.SheetTemplate> SheetTemplates => Set<Domain.Encyclopedia.SheetTemplate>();
    public DbSet<Domain.Encyclopedia.EncyclopediaFolder> EncyclopediaFolders => Set<Domain.Encyclopedia.EncyclopediaFolder>();
    public DbSet<Domain.Encyclopedia.EncyclopediaSheet> EncyclopediaSheets => Set<Domain.Encyclopedia.EncyclopediaSheet>();
    public DbSet<Domain.Notifications.Notification> Notifications => Set<Domain.Notifications.Notification>();
    public DbSet<SceneInvite> SceneInvites => Set<SceneInvite>();
    public DbSet<SceneJoinRequest> SceneJoinRequests => Set<SceneJoinRequest>();
    public DbSet<Domain.Mechanics.InventoryItem> InventoryItems => Set<Domain.Mechanics.InventoryItem>();
    public DbSet<FeaturedItem> FeaturedItems => Set<FeaturedItem>();

    protected override void ConfigureConventions(ModelConfigurationBuilder configuration)
    {
        // Enums are stored as readable text (e.g. "InviteOnly") instead of numbers.
        configuration.Properties<Enum>().HaveConversion<string>().HaveMaxLength(32);
    }

    protected override void OnModelCreating(ModelBuilder builder)
    {
        base.OnModelCreating(builder);

        // Identity tables follow the same snake_case naming as the rest of the schema.
        builder.Entity<User>().ToTable("users");
        builder.Entity<IdentityRole<Guid>>().ToTable("roles");
        builder.Entity<IdentityUserRole<Guid>>().ToTable("user_roles");
        builder.Entity<IdentityUserClaim<Guid>>().ToTable("user_claims");
        builder.Entity<IdentityUserLogin<Guid>>().ToTable("user_logins");
        builder.Entity<IdentityUserToken<Guid>>().ToTable("user_tokens");
        builder.Entity<IdentityRoleClaim<Guid>>().ToTable("role_claims");

        builder.ApplyConfigurationsFromAssembly(typeof(AppDbContext).Assembly);

        // Domain entities create their own Guid ids (Guid.CreateVersion7). Telling EF the key is never
        // generated by the database makes children added through a navigation (e.g. a new revision in
        // Chapter.Revisions) be inserted instead of mistaken for existing rows.
        foreach (var entity in builder.Model.GetEntityTypes())
        {
            if (entity.ClrType.Namespace?.StartsWith("Bookollab.Api.Domain") != true || entity.ClrType == typeof(User)) continue;
            var key = entity.FindPrimaryKey();
            if (key is { Properties: [{ ClrType: var t } keyProperty] } && t == typeof(Guid))
                keyProperty.ValueGenerated = Microsoft.EntityFrameworkCore.Metadata.ValueGenerated.Never;
        }
    }
}
