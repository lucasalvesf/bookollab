import { useQuery } from '@tanstack/react-query';
import { Image } from 'expo-image';
import { useRef, useState } from 'react';
import * as Clipboard from 'expo-clipboard';
import { Copy, Dices, History, Pencil, Trash2, X } from 'lucide-react-native';
import { Pressable, Text, TextInput, View, type ViewInstance } from 'react-native';

import { api } from '@/api/client';
import { unwrap } from '@/api/hooks';
import { Avatar } from '@/components/avatar';
import { ContextMenu, useMenu, type MenuItem } from '@/components/menu';
import { fileUrl } from '@/lib/files';

import type { SceneAction, SceneDetail } from './types';
import { makeStyles, useTheme } from '@/theme';

const timeFmt = new Intl.DateTimeFormat('pt-BR', { hour: '2-digit', minute: '2-digit' });

/** One chat message (an Action). Own messages are on the right; right click (web) or tap opens its menu. */
export function MessageBubble({
  action,
  scene,
  mine,
  grouped,
  onChanged,
}: {
  action: SceneAction;
  scene: SceneDetail;
  mine: boolean;
  /** Same character as the previous message: hide avatar and name. */
  grouped: boolean;
  onChanged: (a: SceneAction) => void;
}) {
  const styles = useStyles();
  const { openMenu, toast } = useMenu();
  const [editing, setEditing] = useState(false);
  const [draft, setDraft] = useState(action.content ?? '');
  const [showHistory, setShowHistory] = useState(false);
  const [error, setError] = useState<string>();
  const open = scene.status === 'Open';
  const bubbleRef = useRef<ViewInstance>(null);
  const roll = action.roll;
  // Rolls are generated by the server: never edited, and only moderators remove them.
  const canEdit = mine && open && !action.deleted && !roll;
  const canDelete = ((mine && !roll) || scene.canModerate) && !action.deleted;
  const canHistory = scene.canViewRevisions && !!action.editedAt && !action.deleted;
  const items: MenuItem[] = [
    { label: 'Copiar texto', icon: Copy, hidden: !action.content || action.deleted, onPress: () => void Clipboard.setStringAsync(action.content ?? '').then(() => toast('Texto copiado')) },
    { label: 'Editar', icon: Pencil, hidden: !canEdit, onPress: () => setEditing(true) },
    { label: showHistory ? 'Ocultar histórico' : 'Histórico de edições', icon: History, hidden: !canHistory, onPress: () => setShowHistory((v) => !v) },
    ...(canDelete
      ? (['separator', {
          label: 'Apagar ação',
          icon: Trash2,
          danger: true,
          onPress: () => openMenu([{ label: 'Apagar de vez', icon: Trash2, danger: true, onPress: () => void remove() }, { label: 'Cancelar', icon: X, onPress: () => undefined }], undefined, 'Apagar esta ação?'),
        }] as MenuItem[])
      : []),
  ];
  const hasMenu = items.some((i) => i !== 'separator' && !i.hidden);

  const history = useQuery({
    queryKey: ['action-revisions', action.id, action.editedAt],
    enabled: showHistory,
    queryFn: () => unwrap(api.GET('/actions/{id}/revisions', { params: { path: { id: action.id } } })),
  });

  async function save() {
    setError(undefined);
    try {
      onChanged(await unwrap(api.PUT('/actions/{id}', { params: { path: { id: action.id } }, body: { content: draft } })));
      setEditing(false);
    } catch (e) {
      setError((e as Error).message);
    }
  }

  async function remove() {
    try {
      await unwrap(api.DELETE('/actions/{id}', { params: { path: { id: action.id } } }));
      onChanged({ ...action, deleted: true, content: null, attachmentKey: null });
    } catch (e) {
      setError((e as Error).message);
    }
  }

  const image = fileUrl(action.attachmentKey);

  return (
    <View style={[styles.row, mine && styles.rowMine, grouped && styles.rowGrouped]}>
      {!mine ? <View style={styles.avatarSlot}>{!grouped ? <Avatar name={action.characterName} imageKey={action.characterAvatarKey} size={38} /> : null}</View> : null}
      <View style={[styles.column, mine && styles.columnMine]}>
        {!grouped ? <Text style={[styles.name, mine && styles.nameMine]}>{action.characterName}</Text> : null}
        <ContextMenu items={editing ? [] : items} title={action.characterName}>
        <Pressable
          ref={bubbleRef}
          accessibilityRole={hasMenu ? 'button' : undefined}
          onPress={() => hasMenu && !editing && bubbleRef.current?.measureInWindow((x, y, w, h) => openMenu(items, { x: mine ? x + w - 248 : x, y: y + h + 4 }, action.characterName))}
          style={[styles.bubble, mine ? styles.bubbleMine : styles.bubbleOther, action.deleted && styles.bubbleDeleted]}>
          {action.deleted ? (
            <Text style={styles.deleted}>Ação apagada</Text>
          ) : editing ? (
            <View style={styles.editBox}>
              <TextInput value={draft} onChangeText={setDraft} multiline style={styles.editInput} accessibilityLabel="Editar ação" autoFocus />
              <View style={styles.inline}>
                <Pressable onPress={save} accessibilityRole="button"><Text style={styles.link}>Salvar</Text></Pressable>
                <Pressable onPress={() => { setEditing(false); setDraft(action.content ?? ''); }} accessibilityRole="button"><Text style={styles.linkMuted}>Cancelar</Text></Pressable>
              </View>
            </View>
          ) : (
            <>
              {image ? <Image source={{ uri: image }} style={styles.image} contentFit="cover" accessibilityLabel="Imagem anexada" /> : null}
              {roll ? (
                <RollCard roll={roll} />
              ) : action.content ? (
                <Text style={[styles.text, mine && styles.textMine]}>{action.content}</Text>
              ) : null}
            </>
          )}
          <Text style={[styles.meta, mine && styles.metaMine]}>
            {action.editedAt && !action.deleted ? 'editada · ' : ''}
            {timeFmt.format(new Date(action.createdAt))}
          </Text>
        </Pressable>
        </ContextMenu>
        {error ? <Text style={styles.error}>{error}</Text> : null}
        {showHistory && history.data ? (
          <View style={styles.history}>
            {history.data.map((r, i) => (
              <Text key={i} style={styles.historyItem}>
                <Text style={styles.historyTime}>{timeFmt.format(new Date(r.createdAt))}  </Text>
                {r.content}
              </Text>
            ))}
          </View>
        ) : null}
      </View>
    </View>
  );
}

/** Dice roll result: expression, each term and the total. */
function RollCard({ roll }: { roll: NonNullable<SceneAction['roll']> }) {
  const styles = useStyles();
  const { colors } = useTheme();
  const detail = roll.terms
    .map((t, i) => {
      const sign = t.sign < 0 ? '− ' : i > 0 ? '+ ' : '';
      const value = t.rolls.length > 0 ? `${t.label} [${t.rolls.join(', ')}]` : t.label === String(t.value) ? t.label : `${t.label} (${t.value})`;
      return sign + value;
    })
    .join(' ');
  return (
    <View style={styles.roll} accessibilityLabel={`Rolagem ${roll.expression}: total ${roll.total}`}>
      <View style={styles.rollHeaderRow}><Dices size={15} color={colors.brand} /><Text style={styles.rollHeader}>{roll.expression}</Text></View>
      <Text style={styles.rollDetail}>{detail}</Text>
      <Text style={styles.rollTotal}>{roll.total}</Text>
    </View>
  );
}

